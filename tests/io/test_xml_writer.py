# ---------------------------------------------------------------------------
# Test 1: full round-trip
# ---------------------------------------------------------------------------


def test_round_trip_full_manifest(tmp_path: Path):
    manifest = _full_manifest(tmp_path)
    out = write_xml(manifest, tmp_path / "manifest.xml")
    parsed = read_xml(out)

    assert parsed.source_path == manifest.source_path
    assert _approx(parsed.source_mtime, manifest.source_mtime)
    assert parsed.source_size == manifest.source_size
    assert parsed.model_version == manifest.model_version
    assert parsed.generated_at == manifest.generated_at
    assert parsed.notes == manifest.notes
    assert len(parsed.parts) == 1

    op = manifest.parts[0]
    pp = parsed.parts[0]
    assert pp.part == op.part
    assert pp.quantity == op.quantity
    assert pp.flat_dxf_path == op.flat_dxf_path

    # Classification
    assert pp.classification.label == op.classification.label
    assert _approx(pp.classification.confidence, op.classification.confidence)
    for cls_name, val in op.classification.trace.scores.items():
        assert _approx(pp.classification.trace.scores[cls_name], val)
    for cls_name, val in op.classification.trace.probabilities.items():
        assert _approx(pp.classification.trace.probabilities[cls_name], val)
    assert _approx(pp.classification.trace.margin, op.classification.trace.margin)
    assert pp.classification.trace.ambiguous == op.classification.trace.ambiguous
    assert pp.classification.trace.tiebreakers_run == op.classification.trace.tiebreakers_run
    assert pp.classification.trace.probe_results == op.classification.trace.probe_results
    assert pp.classification.trace.model_version == op.classification.trace.model_version
    assert len(pp.classification.trace.contributions) == len(op.classification.trace.contributions)
    for parsed_c, orig_c in zip(
        pp.classification.trace.contributions, op.classification.trace.contributions
    ):
        assert parsed_c.feature == orig_c.feature
        assert parsed_c.cls == orig_c.cls
        assert _approx(parsed_c.value, orig_c.value)
        assert _approx(parsed_c.delta, orig_c.delta)

    # Features
    assert pp.features is not None and op.features is not None
    assert _approx(pp.features.volume, op.features.volume)
    assert _approx(pp.features.surface_area, op.features.surface_area)
    for pa, oa in zip(pp.features.bbox_dims_sorted, op.features.bbox_dims_sorted):
        assert _approx(pa, oa)
    assert _approx(pp.features.aspect_ratio, op.features.aspect_ratio)
    assert _approx(pp.features.thickness_ratio, op.features.thickness_ratio)
    assert pp.features.face_area_top == op.features.face_area_top
    assert pp.features.surface_pct == op.features.surface_pct
    assert pp.features.edge_counts == op.features.edge_counts
    assert pp.features.edge_radius == op.features.edge_radius
    assert pp.features.hole_count == op.features.hole_count
    assert pp.features.hole_diameters == op.features.hole_diameters
    assert _approx(pp.features.sa_v_ratio, op.features.sa_v_ratio)
    assert pp.features.is_hollow == op.features.is_hollow
    assert pp.features.inner_shell_count == op.features.inner_shell_count
    assert pp.features.source == op.features.source

    # Profile match
    assert pp.profile_match is not None and op.profile_match is not None
    assert pp.profile_match.family == op.profile_match.family
    assert pp.profile_match.standard == op.profile_match.standard
    assert pp.profile_match.designation == op.profile_match.designation
    assert pp.profile_match.fitted_dims == op.profile_match.fitted_dims
    assert _approx(pp.profile_match.residual_mm, op.profile_match.residual_mm)
    assert _approx(pp.profile_match.confidence, op.profile_match.confidence)

    # Unfold
    assert pp.unfold is not None and op.unfold is not None
    assert pp.unfold.status == op.unfold.status
    assert pp.unfold.n_bends == op.unfold.n_bends
    assert _approx(pp.unfold.flat_area, op.unfold.flat_area)
    assert pp.unfold.blank_bbox == op.unfold.blank_bbox
    assert _approx(pp.unfold.thickness_mean, op.unfold.thickness_mean)
    assert _approx(pp.unfold.thickness_cv, op.unfold.thickness_cv)
    assert pp.unfold.flags == op.unfold.flags

    # Holes
    assert pp.holes is not None and op.holes is not None
    assert pp.holes.hole_count == op.holes.hole_count
    assert pp.holes.diameters == op.holes.diameters


