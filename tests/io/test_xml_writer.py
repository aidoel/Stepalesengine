# Test 4: schema basics
# ---------------------------------------------------------------------------


def test_schema_root_namespace_and_attributes(tmp_path: Path):
    manifest = _full_manifest(tmp_path)
    out = write_xml(manifest, tmp_path / "manifest.xml")

    import xml.etree.ElementTree as ET

    tree = ET.parse(out)
    root = tree.getroot()
    assert root.tag == f"{{{NAMESPACE}}}assembly"
    for required in ("source", "source-mtime", "source-size", "generated-at", "model-version"):
        assert required in root.attrib, f"missing required attr {required}"


# ---------------------------------------------------------------------------
# Test 5: pretty-printing
# ---------------------------------------------------------------------------


def test_pretty_printing_produces_indentation(tmp_path: Path):
    manifest = _full_manifest(tmp_path)
    out = write_xml(manifest, tmp_path / "pretty.xml", pretty=True)
    text = out.read_text(encoding="utf-8")
    assert "\n    " in text  # 4-space-deep indent (2 levels * 2 spaces)
    assert "\n" in text

    out2 = write_xml(manifest, tmp_path / "compact.xml", pretty=False)
    compact = out2.read_text(encoding="utf-8")
    # Compact output should not have those indents.
    assert "\n    " not in compact


