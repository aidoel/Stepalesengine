# Test 3: UTF-8 + special chars
# ---------------------------------------------------------------------------


def test_utf8_and_special_chars_round_trip(tmp_path: Path):
    part = StepPart(
        product_id="UMLAUT-1",
        name='Ühlbrück "Spëcial" Steël & Co. <plate>',
        description="Bréf é à ö ü plaat",
        children=[],
        source="nauo",
    )
    trace = DecisionTrace(
        scores={"plaat": 1.0, "profiel": 0.0, "anders": 0.0},
        probabilities={"plaat": 1.0, "profiel": 0.0, "anders": 0.0},
        margin=1.0,
        ambiguous=False,
        contributions=[],
        tiebreakers_run=[],
        probe_results={},
        model_version="rules-1.0.0",
    )
    manifest = AssemblyManifest(
        source_path="/tmp/Ünëf.stp",
        source_mtime=1.0,
        source_size=1,
        model_version="rules-1.0.0",
        generated_at="2026-05-15T12:00:00Z",
        parts=[
            PartManifestEntry(part=part, classification=ClassificationResult("plaat", 1.0, trace))
        ],
        notes="ä ö é ü <weird & stuff>",
    )
    out = write_xml(manifest, tmp_path / "utf8.xml")
    raw = out.read_bytes()
    # Verify encoded as UTF-8 and the umlauts survive end-to-end.
    assert b"<?xml" in raw
    parsed = read_xml(out)
    assert parsed.parts[0].part.name == part.name
    assert parsed.parts[0].part.description == part.description
    assert parsed.notes == manifest.notes


