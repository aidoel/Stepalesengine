def test_round_trip_two_parts_one_minimal(tmp_path: Path):
    minimal_trace = DecisionTrace(
        scores={"plaat": 0.1, "profiel": 0.0, "anders": 0.9},
        probabilities={"plaat": 0.1, "profiel": 0.0, "anders": 0.9},
        margin=0.8,
        ambiguous=False,
        contributions=[],
        tiebreakers_run=[],
        probe_results={},
        model_version="rules-1.0.0",
    )
    minimal_part = PartManifestEntry(
        part=StepPart(product_id="X-1", name="bolt", description="", children=[], source="nauo"),
        classification=ClassificationResult("anders", 0.9, minimal_trace),
    )

    full = _full_manifest(tmp_path)
    full.parts.append(minimal_part)
    out = write_xml(full, tmp_path / "manifest.xml")
    parsed = read_xml(out)

    assert len(parsed.parts) == 2
    m = parsed.parts[1]
    assert m.features is None
    assert m.profile_match is None
    assert m.unfold is None
    assert m.holes is None
    assert m.flat_dxf_path is None
    assert m.part.product_id == "X-1"
    assert m.classification.label == "anders"


